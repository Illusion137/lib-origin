/** A 64-bit value as [hi, lo] uint32 halves; bit index i is bit 31-i of `lo` for i < 32, bit 63-i of `hi` otherwise. */
type U64 = [number, number];

const bit = (hi: number, lo: number, i: number) => (i < 32 ? (lo >>> (31 - i)) & 1 : (hi >>> (63 - i)) & 1);

function map64(hi: number, lo: number, table: readonly number[]): U64 {
	const half = table.length / 2;
	let out_lo = 0;
	let out_hi = 0;
	for (let i = 0; i < half; i++) {
		if (bit(hi, lo, table[i])) out_lo |= 1 << (31 - i);
		if (bit(hi, lo, table[half + i])) out_hi |= 1 << (31 - i);
	}
	return [out_hi >>> 0, out_lo >>> 0];
}

function map32(value: number, table: readonly number[]): number {
	let out = 0;
	for (let i = 0; i < table.length; i++) if (bit(0, value, table[i])) out |= 1 << (31 - i);
	return out >>> 0;
}

const rotate28 = (x: number, shift: number) => ((x << shift) | ((x >>> (28 - shift)) & 0xfffffff0)) >>> 0;

function key_schedule(key: string, encrypt: boolean): U64[] {
	const bytes = Buffer.from(key, 'latin1');
	const view = new DataView(bytes.buffer, bytes.byteOffset, 8);
	let [d, c] = map64(view.getUint32(4, true), view.getUint32(0, true), PC1);
	const keys = new Array<U64>(16);
	KEY_ROUND_SHIFTS.forEach((shift, i) => {
		c = rotate28(c, shift);
		d = rotate28(d, shift);
		keys[encrypt ? i : 15 - i] = map64(d, c, PC2);
	});
	return keys;
}

/** Runs every whole 8-byte block (little-endian) through the cipher in place. */
function transform(data: Uint8Array, keys: readonly U64[]) {
	const view = new DataView(data.buffer, data.byteOffset, data.byteLength);
	for (let offset = 0; offset + 8 <= data.length; offset += 8) {
		let [hi, lo] = map64(view.getUint32(offset + 4, true), view.getUint32(offset, true), IP);
		for (const [key_hi, key_lo] of keys) {
			const [e_hi, e_lo] = map64(hi, hi, EXPANSION);
			const x_hi = (e_hi ^ key_hi) >>> 0;
			const x_lo = (e_lo ^ key_lo) >>> 0;
			let s = 0;
			SBOX_SHIFTS.forEach((shift, i) => {
				const index = (shift < 32 ? x_lo >>> shift : x_hi >>> (shift - 32)) & 0x3f;
				s = ((s << 4) | SBOXES[i][index]) >>> 0;
			});
			const next = (map32(s, P_BOX) ^ lo) >>> 0;
			lo = hi;
			hi = next;
		}
		[hi, lo] = map64(lo, hi, IP_INV);
		view.setUint32(offset, lo, true);
		view.setUint32(offset + 4, hi, true);
	}
}

let schedules: [U64[], U64[], U64[]] | undefined;

/** Decrypts the hex `lyric` field of a QQ Music `GetPlayLyricInfo` response (`crypt: 1`) to QRC text. Throws on bad input. */
export function decrypt_qrc(hex: string): string {
	if (hex.length % 2 !== 0 || !/^[0-9a-f]*$/iu.test(hex)) throw new Error('QRC: not hex');
	let data = Uint8Array.from(Buffer.from(hex, 'hex'));
	if (QMC_MAGIC.every((b, i) => data[i] === b)) {
		data = data.map((b, i) => b ^ QMC1_KEY[(i > 0x7fff ? i % 0x7fff : i) & 0x7f]).subarray(QMC_MAGIC.length);
	}
	schedules ??= [key_schedule('!@#)(NHL', false), key_schedule('123ZXC!@', true), key_schedule('!@#)(*$%', false)];
	for (const keys of schedules) transform(data, keys);
	return Buffer.from(inflateSync(data)).toString('utf8');
}
